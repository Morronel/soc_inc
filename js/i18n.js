SI.L = function (obj) {
  if (obj == null) return '';
  if (typeof obj === 'string') return obj;
  return obj[SI.lang] != null ? obj[SI.lang] : obj.en;
};

SI.t = function (key, params) {
  var s = (SI.STR[SI.lang] && SI.STR[SI.lang][key]);
  if (s == null) s = SI.STR.en[key];
  if (s == null) return key;
  if (params && typeof s === 'string') {
    s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? params[k] : m; });
  }
  return s;
};

SI.fmt = function (s, params) {
  return String(s).replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? params[k] : m; });
};
